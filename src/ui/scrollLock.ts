/**
 * Запрет прокрутки документа, пока открыто модальное окно.
 *
 * Прокручивается документ, а модальное окно закреплено по центру, и без запрета
 * страница едет у него за спиной: человек крутит колесо, чтобы прочитать что-то
 * в окне, а уезжает то, к чему окно относится. Нативный `<dialog>` сам этого не
 * делает — он запирает только фокус и нажатия.
 *
 * Запрет ставится не `overflow: hidden`, хотя так короче: непрокручиваемый
 * документ теряет положение прокрутки, и окно, открытое из середины длинной
 * страницы, отматывало бы её в начало. Тело закрепляется на месте и сдвигается
 * вверх ровно на то, на сколько страница была прокручена, — картинка не
 * меняется вовсе, а положение возвращается при закрытии.
 *
 * Считаются открытые окна, а не одно: окно правки открывается поверх панели
 * фильтров, и закрытие верхнего не должно отпускать прокрутку.
 *
 * Сдвига вёрстки не будет: место под полосу прокрутки зарезервировано у `html`
 * постоянно (`scrollbar-gutter: stable`), и её исчезновение ничего не двигает.
 */
let open = 0
let offset = 0

export function lockScroll(): () => void {
  if (typeof document === "undefined") return () => {}

  open += 1
  if (open === 1) {
    offset = window.scrollY
    const { style } = document.body
    style.position = "fixed"
    style.top = `-${ offset }px`
    style.left = "0"
    style.right = "0"
  }

  let released = false
  return () => {
    if (released) return
    released = true
    open -= 1
    if (open > 0) return

    const { style } = document.body
    style.position = ""
    style.top = ""
    style.left = ""
    style.right = ""
    if (offset > 0) window.scrollTo({ top: offset })
  }
}
